function wabmap(data, containerId) {
	containerId = containerId || 'mapcontainer';

	if (!wab_squares.responseJSON) { // geojson failed to load (already alerted)
		$(".ld-ext-right-plot").removeClass('running');
		$(".ld-ext-right-plot").prop('disabled', false);
		return;
	}

	var container = L.DomUtil.get('wabmap');

	if(container != null){
		container._leaflet_id = null;
		container.remove();
	}
	$("#" + containerId).append('<div id="wabmap" class="map-leaflet" style="width: 100%;"></div>');
	$('#squaresearch').removeClass('d-none').addClass('d-inline-flex'); // no-op when absent (modal)

	$(".ld-ext-right-plot").removeClass('running');
	$(".ld-ext-right-plot").prop('disabled', false);
	var map = L.map('wabmap',{
		fullscreenControl: true,
		fullscreenControlOptions: {
			position: 'topleft'
		},
		minZoom: 6,
	}).setView([52, -2], 8);
	wabLeafletMap = map; // module-level: also drives highlightSquare()

	var confirmedcount = 0;
	var workedcount = 0;

	// Each square is drawn as a MultiLineString outline plus a Point label, so count unique names
	var totalsquares = new Set(wab_squares.responseJSON.features.filter(function(feature) {
		return feature.geometry.type == 'MultiLineString';
	}).map(function(feature) {
		return feature.properties.name;
	})).size;

	// Squares per DXCC entity (G/GM/GW/GI/GD/GJ/GU), from the generated mapping
	var dxcccounts = {};
	if (wab_dxcc.responseJSON) {
		Object.keys(wab_dxcc.responseJSON).forEach(function(name) {
			var pfx = wab_dxcc.responseJSON[name];
			dxcccounts[pfx] = (dxcccounts[pfx] || 0) + 1;
		});
	}

	// tileUrl/attributionInfo are awards-view-only; footer globals cover the modal
	var tiles = (typeof tileUrl !== 'undefined') ? tileUrl : option_map_tile_server;
	var attribution = (typeof attributionInfo !== 'undefined') ? attributionInfo : option_map_tile_server_copyright;

	L.tileLayer(tiles, {
		attribution: attribution
	}).addTo(map);

	// Add requested external GeoJSON to map
	var geo_wab_squares = L.geoJSON(wab_squares.responseJSON, {
		style: function(feature) {
			if (feature.properties && feature.properties.name) {
				if (data[feature.properties.name] == 'C') {
					confirmedcount++;
					return {
						fillColor: confirmedColor,
						fill: true,
						fillOpacity: 0.8,
						className: 'confirmed-square'
					};
				}
				if (data[feature.properties.name] == 'W') {
					workedcount++;
					return {
						fillColor: workedColor,
						fill: true,
						fillOpacity: 0.8,
						className: 'worked-square'
					};
				}
			}
		},
		pointToLayer: function(feature, latlng) {
			if (feature.properties && feature.properties.name) {
				// my-div-icon gives the label white-space: nowrap (Leaflet's
				// 12x12px default divIcon box would stack the chars vertically)
				var classname = 'my-div-icon text-labels';

				if (data[feature.properties.name] == 'C') {
					classname = 'my-div-icon confirmed-labels';
				}
				if (data[feature.properties.name] == 'W') {
					classname = 'my-div-icon worked-labels';
				}

				// Create a custom icon that displays the name from the GeoJSON data
				var labelIcon = L.divIcon({
					className: classname, // Set class for CSS styling
					html: feature.properties.name
				});

				var sqmarker = L.marker(latlng, {
					icon: labelIcon
				});

				// Create a marker at the location of the point
				return sqmarker;
			}
		},
		onEachFeature: function(feature, layer) {
			layer.on('click', function() {
				// the filter form only exists on the awards page, not the modal
				if (document.getElementById('band') == null) return;
				displayContactsOnMap($("#wabmap"), feature.properties.name, $('#band').val(), $('#sats').val(), $('#orbits').val(), $('#mode').val(), 'WAB');
			});
		}
	}).addTo(map);
	// Function to update labels based on zoom level
	function updateLabels() {
		var currentZoom = map.getZoom();
		geo_wab_squares.eachLayer(function(layer) {
			if (currentZoom >= 8) {
				// Show squares if zoom level is 8 or higher
				layer.getElement().style.display = 'block';
			} else {
				// Hide squares if zoom level is less than 8
				layer.getElement().style.display = 'none';
			}
		});
		if (currentZoom >= 9) {
			$('.text-labels').show();
			$('.leaflet-interactive').show();
		} else if (currentZoom == 8) {
			$('.text-labels').hide();
		} else {
			$('.leaflet-interactive').hide();
			$('.text-labels').hide();
		}
		$('.confirmed-square').show();
		$('.worked-square').show();
	}

	// Update labels when the map zoom changes
	map.on('zoomend', updateLabels);

	// Update labels immediately after adding the GeoJSON data to the map
	updateLabels();

	// Coordinates readout; onMapMove (geocoding.js) is awards-page-only
	if (typeof onMapMove === 'function') {
		map.on('mousemove', onMapMove);
		$('.cohidden').show();
	}

	// Square search: center on the named square, zoom in and highlight it
	wabSquareIndex = {}; // name -> { latlng, ring }
	wab_squares.responseJSON.features.forEach(function(feature) {
		var name = feature.properties.name;
		wabSquareIndex[name] = wabSquareIndex[name] || {};
		if (feature.geometry.type == 'Point') {
			wabSquareIndex[name].latlng = [feature.geometry.coordinates[1], feature.geometry.coordinates[0]];
		} else {
			wabSquareIndex[name].ring = feature.geometry.coordinates[0];
		}
	});

	function gotoSquare() {
		if ($('#wabmap').length == 0) return; // list shown, or map not plotted yet
		var name = $('#squareinput').val().trim().toUpperCase();
		if (wabSquareIndex[name] === undefined) {
			alert(lang_wab_square_not_found);
			return;
		}
		highlightSquare(name);
	}

	$('#squaregoto').off('click').on('click', gotoSquare);
	$('#squareclear').off('click').on('click', function() {
		if (wabSquareHighlight !== null) {
			wabLeafletMap.removeLayer(wabSquareHighlight);
			wabSquareHighlight = null;
		}
		$('#squareinput').val('');
	});
	$('#squareinput').off('keypress').on('keypress', function(e) {
		if (e.which == 13) {
			e.preventDefault();
			gotoSquare();
		}
	});

	var printer = L.easyPrint({
		tileLayer: tiles,
		sizeModes: ['Current', 'A4Landscape', 'A4Portrait'],
		filename: 'Wavelog',
		exportOnly: true,
		hideControlContainer: true
	}).addTo(map);

	/*Legend specific*/
    var legend = L.control({ position: "topright" });

    legend.onAdd = function(map) {
        var div = L.DomUtil.create("div", "legend");
        // fixed-width lead column (swatch/prefix badge), label, right-aligned count
        var row = function(lead, label, count, cls) {
            return "<tr" + (cls ? " class='" + cls + "'" : "") + "><td class='wab-legend-lead'>" + lead + "</td><td>" + label + "</td><td>" + count + "</td></tr>";
        };
        var swatch = function(color) {
            return "<i style='background: " + color + "'></i>";
        };
        var title = function(text) {
            return "<div class='wab-legend-title'>" + text + "</div>";
        };
        var html = title(lang_general_word_colors);
        html += "<table class='wab-legend-table'>";
        html += row(swatch(confirmedColor), lang_general_word_confirmed, confirmedcount);
        html += row(swatch(workedColor), lang_general_word_worked_not_confirmed, workedcount);
        html += row("", lang_wab_total_worked, confirmedcount + workedcount, "wab-legend-total");
        html += "</table>";
        html += "<div class='wab-legend-divider'></div>";
        html += title(lang_wab_squares_by_dxcc);
        html += "<table class='wab-legend-table'>";
        Object.keys(dxcccounts).sort(function(a, b) { return dxcccounts[b] - dxcccounts[a]; }).forEach(function(pfx) {
            html += row("<span class='wab-legend-pfx'>" + pfx + "</span>", wabDxccNames[pfx] || pfx, dxcccounts[pfx]);
        });
        html += row("", lang_wab_total_squares, totalsquares, "wab-legend-total");
        html += "</table>";
        div.innerHTML = html;
        L.DomEvent.disableClickPropagation(div);
        return div;
    };

    // legend needs the lang_wab_* vars (awards view only); skip in the modal
    if (typeof lang_wab_total_worked !== 'undefined') {
        legend.addTo(map);
    }
};

// Tabs + autoload: the active view loads on page load; the other one loads
// lazily on first tab switch. Filter changes (dropdown close) reload the
// active view only, so a hidden map is never built.
var viewLoaded = { map: false, list: false };

function loadActiveView() {
	if (!$('#wabTabs').length) return; // not the awards page (this script is shared with the WAB tool)
	if ($('#wab-map-pane').hasClass('active')) {
		viewLoaded.map = true;
		plotmap();
	} else {
		viewLoaded.list = true;
		showlist();
	}
}

$('#wabTabs button[data-bs-toggle="tab"]').on('shown.bs.tab', function (e) {
	if ($(e.target).attr('data-bs-target') == '#wab-map-pane') {
		$('#squaresearch').removeClass('d-none').addClass('d-inline-flex');
		if (wabLeafletMap !== null) {
			wabLeafletMap.invalidateSize(); // in case it was built while hidden
		}
		if (!viewLoaded.map) loadActiveView();
	} else {
		$('#squaresearch').removeClass('d-inline-flex').addClass('d-none');
		if (!viewLoaded.list) loadActiveView();
	}
});

// any filter change marks both views stale; closing the dropdown reloads the active one
$('.filterbody').on('change', 'select, input', function () {
	viewLoaded.map = false;
	viewLoaded.list = false;
});

$('#wabApply').on('click', function () {
	// closing the dropdown triggers the reload of the active view above
	bootstrap.Dropdown.getOrCreateInstance(document.getElementById('filterDropdown')).hide();
});

$('#filterDropdown').on('hidden.bs.dropdown', function () {
	if ($('#wab-map-pane').hasClass('active')) {
		if (!viewLoaded.map) loadActiveView();
	} else if (!viewLoaded.list) {
		loadActiveView();
	}
});

$(function () {
	loadActiveView();
});

// Show the full worked/confirmed WAB map in a modal, optionally highlighting
// one square and marking the QSO partner's grid with a needle. Shared entry
// point for other pages (the WAB tool); default filters.
function showWabMapModal(square, callsign, lat, lng) {
	var dialog = BootstrapDialog.show({
		title: square ? ('WAB ' + square) : 'WAB',
		size: BootstrapDialog.SIZE_WIDE,
		nl2br: false,
		message: '<div class="text-center p-3"><div class="spinner-border text-primary" role="status"></div></div>',
		buttons: [{ label: 'Close', action: function(d) { d.close(); } }]
	});

	$.ajax({
		url: site_url + '/awards/wab_map',
		type: 'post',
		data: { band: 'All', mode: 'All', sat: 'All', orbit: 'All' },
		success: function(data) {
			// wait for the square/dxcc geojsons before drawing (autoload races these)
			$.when(wab_squares, wab_dxcc).always(function() {
				if (!wab_squares.responseJSON) {
					dialog.setMessage('<div class="alert alert-warning mb-0">WAB square data failed to load.</div>');
					return;
				}
				wabSquareHighlight = null; // stale layer of a previous (closed) map
				dialog.setMessage('<div id="wabmapmodal" style="width:100%;"></div>');
				wabmap(data, 'wabmapmodal');
				L.maidenheadqrb().addTo(wabLeafletMap); // gridsquare overlay (as on the QRB map)
				if (callsign && lat !== null && lng !== null) {
					// QSO partner: same red dot as the QSO dialog map
					L.marker([parseFloat(lat), parseFloat(lng)], { icon: L.icon({ iconUrl: icon_dot_url, iconSize: [18, 18] }) })
						.addTo(wabLeafletMap)
						.bindTooltip(callsign);
				}
				if (square) {
					highlightSquare(square);
				}
				setTimeout(function() {
					if (wabLeafletMap !== null) wabLeafletMap.invalidateSize();
				}, 120);
			});
		},
		error: function() {
			dialog.setMessage('<div class="alert alert-warning mb-0">Error loading map.</div>');
		}
	});
}
